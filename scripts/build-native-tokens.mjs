#!/usr/bin/env node
/**
 * design/design-system/tokens.json (copied from mmPosWeb, the single source)
 *   → src/shared/theme/tokens.generated.ts (React Native values).
 *
 * React Native has no oklch and no rem: colours use the `hex` twin every
 * token already carries, and rem/px strings become numbers (1rem = 16).
 *
 *   node scripts/build-native-tokens.mjs           write the file
 *   node scripts/build-native-tokens.mjs --check   exit 1 if it is stale
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
export const TOKENS_JSON = join(ROOT, 'design/design-system/tokens.json')
export const OUTPUT_TS = join(ROOT, 'src/shared/theme/tokens.generated.ts')

const hex = (token) => (typeof token === 'string' ? token : token.hex)

export function toPx(value) {
  const text = String(value).trim()
  if (text.endsWith('rem')) return Math.round(parseFloat(text) * 16 * 100) / 100
  if (text.endsWith('px')) return parseFloat(text)
  const n = Number(text)
  if (Number.isFinite(n)) return n
  throw new Error(`Cannot convert "${value}" to a number`)
}

const mapValues = (obj, fn) => Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, fn(v)]))

export function buildNativeTokens(json) {
  const c = json.color
  return {
    meta: { source: 'design/design-system/tokens.json', version: json.meta.version },
    color: {
      base100: hex(c.surface.base100),
      base200: hex(c.surface.base200),
      base300: hex(c.surface.base300),
      content: hex(c.text.content),
      ...mapValues(c.brand, hex),
      ...mapValues(c.semantic, hex),
      on: mapValues(c.onColor, hex),
      module: mapValues(c.module, (m) => ({ from: m.from, to: m.to })),
      pageTone: { ...c.pageTone },
      expenseCategory: { ...c.expenseCategory },
      print: mapValues(c.print, hex)
    },
    status: json.color.status,
    opacity: json.opacity,
    fontSize: mapValues(json.typography.scale, toPx),
    fontWeight: json.typography.weight,
    lineHeight: json.typography.lineHeight,
    space: json.space.scale,
    pageGutter: toPx(json.space.pageGutter),
    cardPadding: toPx(json.space.cardPadding),
    cardPaddingLarge: toPx(json.space.cardPaddingLarge),
    radius: mapValues(
      Object.fromEntries(Object.entries(json.radius).filter(([k]) => k !== 'appIcon')),
      (v) => (v === '9999px' ? 9999 : toPx(v))
    ),
    borderWidth: toPx(json.border.width),
    motion: { fast: parseFloat(json.motion.fast), base: parseFloat(json.motion.base) },
    touch: mapValues(
      Object.fromEntries(Object.entries(json.touch).filter(([k]) => k !== 'note')),
      toPx
    ),
    icon: { stroke: json.icon.stroke, sizes: json.icon.sizes }
  }
}

export function renderNativeTokens(json) {
  const tokens = buildNativeTokens(json)
  return [
    '// GENERATED by scripts/build-native-tokens.mjs from design/design-system/tokens.json.',
    '// Do not edit by hand: change mmPosWeb/design, copy it here, then `npm run tokens`.',
    '',
    `export const tokens = ${JSON.stringify(tokens, null, 2)} as const`,
    '',
    'export type Tokens = typeof tokens',
    ''
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rendered = renderNativeTokens(JSON.parse(readFileSync(TOKENS_JSON, 'utf8')))
  if (process.argv.includes('--check')) {
    let current = ''
    try {
      current = readFileSync(OUTPUT_TS, 'utf8')
    } catch {
      /* missing → stale */
    }
    if (current !== rendered) {
      console.error('tokens.generated.ts is stale: run `npm run tokens`')
      process.exit(1)
    }
    console.log('tokens.generated.ts is up to date')
  } else {
    writeFileSync(OUTPUT_TS, rendered)
    console.log('wrote', OUTPUT_TS)
  }
}
